def add(a, b):
    return a + b


def subtract(a, b):
    return a - b

def multiply(a, b):
    return a * b

def square(a):
    return a * a

def divide(a,b):
    return a/b

print("Addition:", add(10, 20))
print("Subtraction:", subtract(20, 10))
print("Multiplication:", multiply(10, 5))
print("Square", square(4))
print("divide", divide(10,2))
